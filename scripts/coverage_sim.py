"""Monte-Carlo calibration of Passk's inference. Writes docs/coverage.md. Run: python scripts/coverage_sim.py
Design: task reliabilities p_t ~ Beta(2,1) (true population pass^k = 2/(k+2)); 40 tasks x 5 trials."""
import random
import sys
import time
from pathlib import Path

from passk import stats
from passk.compare import compare
from passk.logs import Trial, TrialTable

SIMS = int(sys.argv[1]) if len(sys.argv) > 1 else 400
BOOT = 300


def draw(rng, m, n, a=2.0, b=1.0):
    return [(n, sum(rng.random() < (p := rng.betavariate(a, b)) for _ in range(n)), p)[:2] for _ in range(m)]


def tasks(rng, m, n):
    out = []
    for _ in range(m):
        p = rng.betavariate(2, 1)
        out.append((n, sum(rng.random() < p for _ in range(n))))
    return out


def table(rates, n, rng):
    t = TrialTable()
    for i, p in enumerate(rates):
        for e in range(n):
            t.trials.append(Trial("x", f"t{i}", e + 1, rng.random() < p, "m"))
    return t


t0 = time.time()
rows = []
for k in (1, 2, 3, 5):
    truth = 2.0 / (k + 2)
    rng = random.Random(100 + k)
    cov = {"two-stage, Jeffreys-smoothed (default)": 0, "two-stage, plug-in p-hat (rejected)": 0,
           "task-only percentile bootstrap": 0}
    for s in range(SIMS):
        t = tasks(rng, 40, 5)
        lo, hi = stats.cluster_bootstrap_pass(t, k, reps=BOOT, seed=s)
        cov["two-stage, Jeffreys-smoothed (default)"] += lo <= truth <= hi
        lo, hi = stats.cluster_bootstrap_pass(t, k, reps=BOOT, seed=s, smooth=False)
        cov["two-stage, plug-in p-hat (rejected)"] += lo <= truth <= hi
        vals = [stats.ph(n, c, k) for n, c in t]
        lo, hi = stats.percentile_ci(vals, reps=BOOT, seed=s)
        cov["task-only percentile bootstrap"] += lo <= truth <= hi
    for name, c in cov.items():
        rows.append((f"pass^{k}", name, c / SIMS))

rng = random.Random(7)
rates = [rng.betavariate(2, 1) for _ in range(30)]
fp = sum(compare(table(rates, 6, rng), table(rates, 6, rng), 1, reps=150, seed=s).verdict != "inconclusive"
         for s in range(SIMS // 4))
worse = [max(0.0, p - 0.25) for p in rates]
pw = sum(compare(table(rates, 6, rng), table(worse, 6, rng), 1, reps=150, seed=s).verdict == "regressed"
         for s in range(SIMS // 4))

lines = ["# Calibration (generated by `scripts/coverage_sim.py`)", "",
         f"{SIMS} simulated experiments per row; 40 tasks x 5 trials; task reliabilities ~ Beta(2,1); "
         f"{BOOT} bootstrap replicates; nominal level 95%. Monte-Carlo standard error is about 1 point.", "",
         "| target | method | achieved coverage |", "| --- | --- | --- |"]
lines += [f"| {a} | {b} | {c:.1%} |" for a, b, c in rows]
lines += ["", "## Paired comparison (30 tasks x 6 trials per side, alpha = 0.05)", "",
          f"- Type-I error (identical reliabilities, non-inconclusive verdict): {fp / (SIMS // 4):.1%}",
          f"- Power (true drop of 0.25 per task, verdict `regressed`): {pw / (SIMS // 4):.1%}", "",
          f"Runtime {time.time() - t0:.0f}s. The plug-in two-stage variant was the first implementation; this table is why it was replaced.", ""]
Path("docs").mkdir(exist_ok=True)
Path("docs/coverage.md").write_text("\n".join(lines))
print("\n".join(lines))
